    a.InTime = na.InTime,
    a.OutTime = na.OutTime,
    a.Duration = na.Duration,
    a.Status = na.Status,
    a.Remarks = na.Remarks
FROM dbo.AttendanceLogs a
JOIN dbo.Employees e ON a.EmployeeId = e.EmployeeId
JOIN #NewAttendance na 
    ON (LTRIM(RTRIM(CAST(e.EmployeeCode AS VARCHAR(50)))) = na.EmployeeCode OR LTRIM(RTRIM(CAST(e.EmployeeCode AS VARCHAR(50)))) = LTRIM(RTRIM(na.EmployeeCode)))
   AND CAST(a.AttendanceDate AS DATE) = na.AttendanceDate;

