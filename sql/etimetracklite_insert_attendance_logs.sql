    ON (LTRIM(RTRIM(CAST(e.EmployeeCode AS VARCHAR(50)))) = na.EmployeeCode OR LTRIM(RTRIM(CAST(e.EmployeeCode AS VARCHAR(50)))) = LTRIM(RTRIM(na.EmployeeCode)))
