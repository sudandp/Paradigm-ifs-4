/**
 * Returns optimized PostgREST filter parameters for site queries.
 * Known sites use equality/IN filters to leverage composite B-Tree indexes (4ms vs 340ms).
 */
export function getSiteFilterParam(rawSite: string): { filterParam: string; isKnown: boolean; exactName: string } {
  const clean = String(rawSite || '').toLowerCase().trim();
  if (!clean || clean === 'all') {
    return { filterParam: '', isKnown: false, exactName: 'all' };
  }

  for (const [key, config] of Object.entries(KNOWN_SITES)) {
    if (clean.includes(key)) {
      return { filterParam: config.postgrestParam, isKnown: true, exactName: config.exactName };
    }
  }

  return {
    filterParam: `site=ilike.*${encodeURIComponent(rawSite)}*`,
    isKnown: false,
    exactName: rawSite,
  };
}

// ─── 2. Biometric Punch & Time Sanitization ──────────────────────────────────

/**
 * Identifies null, empty, or dummy midnight timestamps generated by sensors.
 */
export function isDummyTimeVal(t: string | undefined | null): boolean {
  if (!t || t === '—' || t === '-') return true;
  const clean = t.trim().toLowerCase();
  return (
    clean === '12:00 am' ||
    clean === '00:00' ||
    clean === '00:00:00' ||
    clean === '12:00:00 am' ||
    clean === '00:00:00 am'
  );
}

// ─── 3. Multi-Shift, Double Duty & Status Heuristics ─────────────────────────

export interface ShiftResolution {
  isPres: boolean;
  isLate: boolean;
  isDouble: boolean;
  isTriple: boolean;
  duties: number;
  statusStr: string;
  shiftName: string;
  shiftCode: string;
  durationMins: number;
  otMins: number;
}

/**
 * Evaluates shift code, double-duty multiplier, and presence status
 * following the Paradigm Dynamic Shift Engine standards.
 */
export function resolveShiftAndDuties(record: any, isWeeklyOff: boolean): ShiftResolution {
  if (isWeeklyOff) {
    return {
      isPres: false,
      isLate: false,
      isDouble: false,
      isTriple: false,
      duties: 0,
      statusStr: 'WO',
      shiftName: 'Weekly Off',
      shiftCode: 'WO',
      durationMins: 0,
      otMins: 0,
    };
  }

  const rawIn = record.in_time || record.inTime || '';
  const rawOut = record.out_time || record.outTime || '';
  const durationMins = Number(record.duration_mins ?? record.durationMins ?? record.duration ?? 0);
  const otMins = Number(record.ot_mins ?? record.otMins ?? 0);
  const lateMins = Number(record.late_mins ?? record.lateMinutes ?? 0);

  const hasRealIn = Boolean(rawIn) && !isDummyTimeVal(rawIn);
  const hasRealOut = Boolean(rawOut) && !isDummyTimeVal(rawOut);
  const hasDuration = durationMins >= 240;

  const rawStatus = String(record.status || '').toLowerCase();
  const rawStatusCode = String(record.status_code || record.statusCode || '').toUpperCase();

  const isPres =
    (hasRealIn || hasRealOut || hasDuration) &&
    (rawStatus === 'present' || rawStatusCode === 'P' || hasRealIn || hasRealOut);

  const isLate = (rawStatus === 'late' || lateMins > 0) && (hasRealIn || hasDuration);

  // Triple duty check (>= 21 hours or explicit flag)
  const isTriple =
    record.shiftType === 'triple' ||
    String(record.shiftName || '').includes('A + B + C') ||
    String(record.shiftName || '').includes('A+B+C') ||
    durationMins >= 1260;

  // Double duty check (>= 14 hours / 840 mins continuous span or split morning+night)
  const isDouble =
    !isTriple &&
    (record.shiftType === 'double' ||
      String(record.shiftName || '').includes('+') ||
      (otMins >= 360 && durationMins >= 660) ||
      durationMins >= 840);

  const duties = isTriple ? 3 : isDouble ? 2 : 1;

  let statusStr = 'A';
  if (isPres) statusStr = 'P';
  else if (isLate) statusStr = 'L';

  // Shift assignment heuristics based on punch timestamp
  let shiftName = isTriple ? 'A + B + C Shift (Triple Duty)' : isDouble ? 'B + C Shift Group' : 'A Shift Group';
  let shiftCode = isTriple ? 'A+B+C' : isDouble ? 'B+C' : 'A';

  if (!isDouble && !isTriple && hasRealIn) {
    const cleanIn = rawIn.toLowerCase();
    if (
      cleanIn.includes('pm') &&
      (cleanIn.startsWith('09') ||
        cleanIn.startsWith('10') ||
        cleanIn.startsWith('11') ||
        cleanIn.startsWith('08') ||
        cleanIn.startsWith('07'))
    ) {
      shiftName = 'C Shift Group (Night)';
      shiftCode = 'C';
    } else if (
      cleanIn.includes('pm') ||
      cleanIn.startsWith('12') ||
      cleanIn.startsWith('01') ||
      cleanIn.startsWith('02') ||
      cleanIn.startsWith('03')
    ) {
      shiftName = 'B Shift Group (Afternoon)';
      shiftCode = 'B';
    }
  }

  return {
    isPres,
    isLate,
    isDouble,
    isTriple,
    duties,
    statusStr,
    shiftName,
    shiftCode,
    durationMins,
    otMins,
  };
}

// ─── 4. Record Aggregation & Normalization ───────────────────────────────────

/**
 * Merges raw rows from either Supabase cache or remote MSSQL proxy into structured employee day-maps.
 */
export function processAttendanceRowsIntoRecords(
  rows: any[],
  siteFilter: string = 'all'
): { records: Record<string, AttendanceEmployeeRecord>; employees: AttendanceEmployeeRecord[] } {
  const records: Record<string, AttendanceEmployeeRecord> = {};
  const filterLower = siteFilter.toLowerCase().trim();

  for (const r of rows) {
    const code = String(r.emp_code || r.empCode || '').trim();
    if (!code) continue;

    const rawSite = r.site && r.site !== 'Default' ? r.site : r.department || 'General';
    const smartSite = String(rawSite).trim();

    // Client-side site boundary filtering
    if (filterLower && filterLower !== 'all') {
      const cSite = smartSite.toLowerCase();
      const matchesSite = cSite.includes(filterLower) || filterLower.includes(cSite);
      const matchesUtopiaPrefix = filterLower.includes('utopia') && (code.startsWith('31') || code.startsWith('32'));
      if (!matchesSite && !matchesUtopiaPrefix) {
        continue;
      }
    }

    if (!records[code]) {
      records[code] = {
        empCode: code,
        empName: r.emp_name || r.empName || 'Staff',
        department: smartSite,
        designation: r.designation || 'Staff',
        company: r.company || (code.startsWith('32') ? 'Southwall Security LLP' : 'PIFS'),
        days: {},
        summary: { presentDays: 0, absentDays: 0, woDays: 0, lateDays: 0, totalNetMins: 0, totalOtMins: 0 },
      };
    }

    const dStr = r.attendance_date || r.dateStr || r.date;
    if (!dStr) continue;

    const isWO =
      r.status === 'Weekly Off' ||
      r.status === 'WO' ||
      r.status_code === 'WO' ||
      r.status_code === 'W/O' ||
      r.isWeeklyOff === true;

    const shift = resolveShiftAndDuties(r, isWO);

    // Update cumulative summary
    if (isWO) {
      records[code].summary.woDays += 1;
    } else if (shift.isPres || shift.isLate) {
      records[code].summary.presentDays += shift.duties;
      if (shift.isLate) records[code].summary.lateDays++;
    } else {
      records[code].summary.absentDays++;
    }

    records[code].summary.totalNetMins += shift.durationMins;
    records[code].summary.totalOtMins += shift.otMins;

    const rawIn = r.in_time || r.inTime || '';
    const rawOut = r.out_time || r.outTime || '';

    records[code].days[dStr] = {
      dateStr: dStr,
      inTime: !isWO && !isDummyTimeVal(rawIn) ? rawIn : '—',
      outTime: !isWO && !isDummyTimeVal(rawOut) ? rawOut : '—',
      hours: r.working_hours && r.working_hours !== '—' ? r.working_hours : shift.isPres ? '9h 00m' : '—',
      status: shift.statusStr,
      shiftType: shift.isTriple ? 'triple' : shift.isDouble ? 'double' : 'single',
      shiftName: shift.shiftName,
      shiftCode: shift.shiftCode,
      totalDuties: isWO ? 0 : shift.duties,
      isWeeklyOff: isWO,
      lateMinutes: Number(r.late_mins ?? r.lateMinutes ?? 0),
      durationMins: shift.durationMins,
      otMins: shift.otMins,
    };
  }

  const employees = Object.values(records);
  return { records, employees };
}
