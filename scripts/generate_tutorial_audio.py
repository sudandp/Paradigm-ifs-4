async def generate_audio(step_key: str, lang: str, text: str):
    voice = VOICES.get(lang, "en-IN-NeerjaNeural")
    filename = f"{step_key}_{lang}.mp3"
    filepath = os.path.join(OUTPUT_DIR, filename)

    print(f"Generating [{lang}] {step_key} -> {filename}...")
    communicate = edge_tts.Communicate(text, voice)
    await communicate.save(filepath)
    print(f"Saved: {filename} ({os.path.getsize(filepath):,} bytes)")

async def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    tasks = []
    for step_key, lang_dict in SCRIPTS.items():
        for lang, text in lang_dict.items():
            tasks.append(generate_audio(step_key, lang, text))
    
    await asyncio.gather(*tasks)
    print(f"\nSuccessfully generated all {len(tasks)} studio audio clips in {OUTPUT_DIR}!")

if __name__ == "__main__":
    asyncio.run(main())
