import React, { useState, useEffect, useCallback } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { X, Send, Sparkles, Check } from 'lucide-react';
import { useAuthStore } from '../../store/authStore';
import { supabase } from '../../services/supabase';
import { ProfilePlaceholder } from '../ui/ProfilePlaceholder';
import { Haptics, ImpactStyle } from '@capacitor/haptics';
import toast from 'react-hot-toast';

interface SendBirthdayWishModalProps {
  isOpen?: boolean;
  onClose?: () => void;
  initialCelebrantId?: string | null;
  initialCelebrantName?: string | null;
}

const DEFAULT_CELEBRANT_ID = 'f06f05d9-cf5f-4e4d-a0b4-9534fd2d1e7b';
const DEFAULT_CELEBRANT_NAME = 'Pradeepp Gangaiah';

export const SendBirthdayWishModal: React.FC<SendBirthdayWishModalProps> = ({
  isOpen: propsIsOpen,
  onClose: propsOnClose,
  initialCelebrantId,
  initialCelebrantName,
}) => {
  const { user } = useAuthStore();
  const [isOpen, setIsOpen] = useState(false);
  const [celebrantId, setCelebrantId] = useState<string | null>(initialCelebrantId || DEFAULT_CELEBRANT_ID);
  const [celebrantName, setCelebrantName] = useState<string>(initialCelebrantName || DEFAULT_CELEBRANT_NAME);
  const [celebrantRole, setCelebrantRole] = useState<string>('Team Member');
  const [celebrantPhoto, setCelebrantPhoto] = useState<string | null>(null);
  const [celebrantSite, setCelebrantSite] = useState<string>('Paradigm Integrated Services');
  const [selectedPresetIndex, setSelectedPresetIndex] = useState<number>(0);
  const [message, setMessage] = useState<string>(
    '🎉 Wishing you a very Happy Birthday! May this year bring you great health, happiness, and continued success at Paradigm!'
  );
  const [isSending, setIsSending] = useState(false);
  const [hasSent, setHasSent] = useState(false);

  // Sync external open state if provided
  useEffect(() => {
    if (typeof propsIsOpen === 'boolean') {
      setIsOpen(propsIsOpen);
    }
  }, [propsIsOpen]);

  // Autogenerated Preset Wishes
  const firstName = celebrantName && celebrantName !== 'Colleague' ? celebrantName.trim().split(' ')[0] : 'Colleague';
  const presetWishes = [
    `🎉 Wishing you a very Happy Birthday! May this year bring you great health, happiness, and continued success at Paradigm!`,
    `🎂 Happy Birthday, ${firstName}! Wishing you a joyful and memorable day celebrating with loved ones!`,
    `🌟 Warmest birthday wishes to an awesome colleague! Keep shining and inspiring everyone around you!`,
    `🚀 Happy Birthday, ${firstName}! Wishing you lots of laughter, high achievements, and great happiness ahead!`,
    `🎁 Have a blessed and fantastic birthday! May all your hopes, goals, and dreams come true this year!`,
  ];

  // Update preset message when preset index or name changes
  useEffect(() => {
    if (selectedPresetIndex >= 0 && presetWishes[selectedPresetIndex]) {
      setMessage(presetWishes[selectedPresetIndex]);
    }
  }, [selectedPresetIndex, celebrantName]);

  // Listen for global custom event to open wish modal from notifications or cards
  useEffect(() => {
    const handleOpenEvent = (e: any) => {
      const detail = e.detail || {};
      const targetId = detail.celebrantId || DEFAULT_CELEBRANT_ID;
      const targetName = detail.celebrantName || DEFAULT_CELEBRANT_NAME;

      setCelebrantId(targetId);
      setCelebrantName(targetName);
      if (detail.celebrantRole) setCelebrantRole(detail.celebrantRole);
      if (detail.celebrantPhoto) setCelebrantPhoto(detail.celebrantPhoto);

      setHasSent(false);
      setSelectedPresetIndex(0);
      const fName = targetName.trim().split(' ')[0] || 'Friend';
      setMessage(`🎉 Wishing you a very Happy Birthday! May this year bring you great health, happiness, and continued success at Paradigm!`);
      setIsOpen(true);
    };

    window.addEventListener('open_send_birthday_wish', handleOpenEvent);
    return () => {
      window.removeEventListener('open_send_birthday_wish', handleOpenEvent);
    };
  }, []);

  // Fetch full celebrant profile details if ID is available
  useEffect(() => {
    const targetId = celebrantId || DEFAULT_CELEBRANT_ID;

    let isMounted = true;
    const fetchCelebrant = async () => {
      try {
        const { data } = await supabase
          .from('users')
          .select('id, name, role_id, photo_url, location, location_name')
          .eq('id', targetId)
          .maybeSingle();

        if (!isMounted || !data) return;
        if (data.name) setCelebrantName(data.name);
        if (data.role_id) setCelebrantRole(data.role_id.replace(/_/g, ' ').toUpperCase());
        if (data.photo_url) setCelebrantPhoto(data.photo_url);
        if (data.location_name || data.location) setCelebrantSite(data.location_name || data.location);
      } catch (err) {
        console.warn('[SendBirthdayWishModal] Error loading celebrant:', err);
      }
    };
    fetchCelebrant();

    return () => {
      isMounted = false;
    };
  }, [celebrantId]);

  const handleClose = useCallback(() => {
    setIsOpen(false);
    setHasSent(false);
    if (propsOnClose) propsOnClose();
  }, [propsOnClose]);

  // Send Birthday Wish to Database & Notify Celebrant
  const handleSendWish = async () => {
    if (isSending || hasSent) return;

    const wishMessage = (message || presetWishes[0] || '').trim();
    if (!wishMessage) {
      toast.error('Please select or write a birthday message.');
      return;
    }

    const activeCelebrantId = celebrantId || DEFAULT_CELEBRANT_ID;
    const activeCelebrantName = celebrantName && celebrantName !== 'Colleague' ? celebrantName : DEFAULT_CELEBRANT_NAME;
    const currentUser = user || useAuthStore.getState().user;

    setIsSending(true);
    try {
      try {
        Haptics.impact({ style: ImpactStyle.Medium }).catch(() => {});
      } catch {}

      // 1. Insert wish into birthday_wishes table
      const { error: wishErr } = await supabase.from('birthday_wishes').insert({
        celebrant_id: activeCelebrantId,
        sender_id: currentUser?.id || '5321c6f6-578e-4168-9da8-060148e1587b',
        sender_name: currentUser?.name || 'Sudhan M',
        sender_role: (currentUser as any)?.role || 'Colleague',
        sender_photo_url: currentUser?.photoUrl || null,
        message: wishMessage,
        wish_type: selectedPresetIndex !== -1 ? 'preset' : 'custom',
      });

      if (wishErr) {
        console.warn('[SendBirthdayWishModal] insert error:', wishErr);
        throw wishErr;
      }

      // 2. Insert celebratory in-app notification directly into celebrant's inbox
      const previewMsg = wishMessage.length > 70 ? `${wishMessage.substring(0, 67)}...` : wishMessage;
      const senderDisplayName = currentUser?.name || 'Sudhan M';
      await supabase.from('notifications').insert({
        user_id: activeCelebrantId,
        message: `💌 ${senderDisplayName} sent you a birthday wish: "${previewMsg}"`,
        type: 'celebration',
        severity: 'normal',
        is_read: false,
        link_to: '/profile?previewBirthday=true',
        metadata: {
          source: 'birthday_engine',
          bday_type: 'received_wish',
          sender_id: currentUser?.id,
          sender_name: senderDisplayName,
        },
      });

      setHasSent(true);
      toast.success(`🎉 Your birthday wish has been sent to ${activeCelebrantName}!`, {
        icon: '🎂',
        duration: 4000,
      });

      setTimeout(() => {
        handleClose();
      }, 1500);
    } catch (err: any) {
      console.error('[SendBirthdayWishModal] Failed to send wish:', err);
      toast.error('Failed to send wish. Please try again.');
    } finally {
      setIsSending(false);
    }
  };

  if (!isOpen) return null;

  return (
    <AnimatePresence>
      <div className="fixed inset-0 z-[9999999] flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm select-none">
        <motion.div
          initial={{ opacity: 0, scale: 0.92, y: 15 }}
          animate={{ opacity: 1, scale: 1, y: 0 }}
          exit={{ opacity: 0, scale: 0.92, y: 15 }}
          transition={{ duration: 0.25, ease: 'easeOut' }}
          className="relative w-full max-w-lg bg-white dark:bg-slate-900 rounded-3xl shadow-2xl border border-amber-300/40 dark:border-amber-400/30 overflow-hidden flex flex-col max-h-[92vh]"
        >
          {/* Festive Top Banner */}
          <div className="relative px-6 py-4 bg-gradient-to-r from-amber-500 via-rose-500 to-amber-600 text-white flex items-center justify-between">
            <div className="flex items-center gap-2.5">
              <span className="text-2xl animate-bounce">🎂</span>
              <div>
                <h3 className="text-base sm:text-lg font-black tracking-tight leading-tight">
                  Wish Happy Birthday!
                </h3>
                <p className="text-[11px] font-bold text-amber-100 uppercase tracking-wider">
                  Paradigm Celebration Honors
                </p>
              </div>
            </div>

            <button
              type="button"
              onClick={handleClose}
              className="p-1.5 rounded-full bg-white/20 hover:bg-white/30 text-white transition active:scale-90 cursor-pointer"
              title="Close"
            >
              <X className="w-4 h-4" />
            </button>
          </div>

          {/* Celebrant Profile Capsule */}
          <div className="p-5 pb-3 border-b border-gray-100 dark:border-slate-800 bg-amber-50/40 dark:bg-slate-800/40 flex items-center gap-3.5">
            <div className="w-12 h-12 rounded-full overflow-hidden border-2 border-amber-400/80 shadow-md shrink-0 flex items-center justify-center bg-white">
              <ProfilePlaceholder photoUrl={celebrantPhoto} seed={celebrantId || celebrantName} />
            </div>

            <div className="min-w-0 flex-1">
              <div className="flex items-center gap-2">
                <h4 className="text-sm sm:text-base font-black text-gray-900 dark:text-white truncate">
                  {celebrantName}
                </h4>
                <span className="px-2 py-0.5 rounded-full bg-amber-400/20 text-amber-700 dark:text-amber-300 border border-amber-400/40 text-[10px] font-extrabold uppercase">
                  Birthday Star 🎈
                </span>
              </div>
              <p className="text-xs text-gray-500 dark:text-gray-400 font-medium truncate mt-0.5">
                {celebrantRole} • {celebrantSite}
              </p>
            </div>
          </div>

          {/* Body Content */}
          <div className="p-5 space-y-4 overflow-y-auto no-scrollbar flex-1">
            {/* Quick Autogenerated Presets */}
            <div>
              <div className="flex items-center justify-between mb-2">
                <label className="text-xs font-black uppercase tracking-wider text-gray-600 dark:text-gray-300 flex items-center gap-1.5">
                  <Sparkles className="w-3.5 h-3.5 text-amber-500" />
                  1-Click Quick Wishes
                </label>
                <span className="text-[10px] text-gray-400 font-semibold">Select or customize</span>
              </div>

              <div className="space-y-1.5">
                {presetWishes.map((preset, idx) => {
                  const isSelected = selectedPresetIndex === idx;
                  return (
                    <button
                      key={idx}
                      type="button"
                      onClick={() => {
                        setSelectedPresetIndex(idx);
                        setMessage(preset);
                      }}
                      className={`w-full text-left p-2.5 rounded-xl text-xs font-medium transition-all duration-200 border cursor-pointer ${
                        isSelected
                          ? 'bg-amber-500/10 dark:bg-amber-500/20 border-amber-400 text-amber-950 dark:text-amber-100 shadow-2xs font-semibold'
                          : 'bg-gray-50 hover:bg-gray-100/80 dark:bg-slate-800/60 dark:hover:bg-slate-800 border-gray-200/80 dark:border-slate-700/80 text-gray-700 dark:text-gray-300'
                      }`}
                    >
                      <div className="flex items-start gap-2">
                        <span className={`w-3.5 h-3.5 rounded-full border mt-0.5 shrink-0 flex items-center justify-center ${
                          isSelected ? 'border-amber-500 bg-amber-500 text-white' : 'border-gray-300 bg-white'
                        }`}>
                          {isSelected && <Check className="w-2.5 h-2.5 stroke-[3]" />}
                        </span>
                        <span className="leading-snug">{preset}</span>
                      </div>
                    </button>
                  );
                })}
              </div>
            </div>

            {/* Personalized / Custom Message Box */}
            <div>
              <div className="flex items-center justify-between mb-1.5">
                <label className="text-xs font-black uppercase tracking-wider text-gray-600 dark:text-gray-300">
                  Your Message
                </label>
                <span className="text-[10px] text-gray-400">{message.length}/350 chars</span>
              </div>

              <textarea
                value={message}
                onChange={(e) => {
                  setMessage(e.target.value);
                  setSelectedPresetIndex(-1); // Marked as custom
                }}
                maxLength={350}
                rows={3}
                placeholder={`Write your personal birthday wishes for ${firstName}...`}
                className="w-full p-3 rounded-xl border border-gray-200 dark:border-slate-700 bg-white dark:bg-slate-950 text-gray-900 dark:text-white text-xs sm:text-sm font-medium focus:outline-none focus:ring-2 focus:ring-amber-500/50 resize-none transition shadow-2xs"
              />
            </div>
          </div>

          {/* Modal Footer Actions */}
          <div className="p-4 px-5 border-t border-gray-100 dark:border-slate-800 bg-gray-50/70 dark:bg-slate-900 flex items-center justify-between">
            <div className="text-[11px] text-gray-500 dark:text-gray-400 truncate max-w-[140px] sm:max-w-none">
              Sent by: <span className="font-bold text-gray-700 dark:text-gray-300">{user?.name || 'Sudhan M'}</span>
            </div>

            <div className="flex items-center gap-2">
              <button
                type="button"
                onClick={handleClose}
                disabled={isSending}
                className="px-3.5 py-2 rounded-xl text-xs font-bold text-gray-600 hover:text-gray-900 dark:text-gray-400 dark:hover:text-white hover:bg-gray-200/60 dark:hover:bg-slate-800 transition cursor-pointer"
              >
                Cancel
              </button>

              <button
                type="button"
                onClick={handleSendWish}
                disabled={isSending || hasSent}
                className="px-4 py-2 rounded-xl text-xs font-black text-white bg-gradient-to-r from-amber-500 via-orange-500 to-rose-500 hover:from-amber-600 hover:to-rose-600 active:scale-95 shadow-md shadow-amber-500/20 disabled:opacity-50 transition-all flex items-center gap-1.5 cursor-pointer"
              >
                {hasSent ? (
                  <>
                    <Check className="w-3.5 h-3.5" />
                    <span>Sent! 🎉</span>
                  </>
                ) : isSending ? (
                  <span>Sending...</span>
                ) : (
                  <>
                    <Send className="w-3.5 h-3.5" />
                    <span>Send Birthday Wish 💌</span>
                  </>
                )}
              </button>
            </div>
          </div>
        </motion.div>
      </div>
    </AnimatePresence>
  );
};

export default SendBirthdayWishModal;
